#!/usr/bin/env python3
"""「アプリケーション」フォルダと「ユーティリティ」フォルダを作る。

Mac の /Applications と同じように、アプリの起動ファイル (.desktop) を実際のフォルダに並べる。
Thunar で開くとアイコンが並び、ダブルクリックで起動できる。

使い方: scripts/gen-applications-folder.py [出力先 (既定: /Applications)]
分類:   config/utilities.txt (ユーティリティ)、config/prefs-apps.txt (入れない)、
        メニューから隠したもの (config/skel/.local/share/applications) も入れない。
        どれにも当てはまらないアプリは、フォルダの直下に入る。
"""
import os
import shutil
import sys

# 隠す設定を反映するため、skel の applications を先に見る
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
os.environ["XDG_DATA_HOME"] = os.path.join(ROOT, "config", "skel", ".local", "share")

import gi  # noqa: E402

gi.require_version("Gio", "2.0")
from gi.repository import Gio  # noqa: E402

MARK = "# generated by gen-applications-folder.py\n"


def read_list(name):
    path = os.path.join(ROOT, "config", name)
    out = set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                out.add(line)
    return out


def clean(folder):
    """前回の生成物を消す (分類から外したアプリを元に戻すため)。"""
    if not os.path.isdir(folder):
        return
    for name in os.listdir(folder):
        p = os.path.join(folder, name)
        if name.endswith(".desktop") and os.path.isfile(p):
            with open(p, encoding="utf-8", errors="replace") as f:
                if f.readline() == MARK:
                    os.remove(p)


def read_overrides():
    out = {}
    path = os.path.join(ROOT, "config", "icon-overrides.txt")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    out[k] = v
    return out


ICON_OVERRIDES = read_overrides()


def write(folder, app):
    src = app.get_filename()
    with open(src, encoding="utf-8", errors="replace") as f:
        body = f.read()
    app_id = os.path.basename(src).removesuffix(".desktop")
    if app_id in ICON_OVERRIDES:
        lines = body.split("\n")
        for i, line in enumerate(lines):
            if line.startswith("Icon="):
                lines[i] = "Icon=" + ICON_OVERRIDES[app_id]
                break
        body = "\n".join(lines)
    dst = os.path.join(folder, os.path.basename(src))
    with open(dst, "w", encoding="utf-8") as f:
        f.write(MARK + body)
    os.chmod(dst, 0o755)   # 実行ビットがないと Thunar が「信頼できない起動ファイル」と警告する


def main():
    dest = sys.argv[1] if len(sys.argv) > 1 else "/Applications"
    utils_dir = os.path.join(dest, "Utilities")
    utilities, prefs = read_list("utilities.txt"), read_list("prefs-apps.txt")

    os.makedirs(utils_dir, exist_ok=True)
    clean(dest)
    clean(utils_dir)

    n_apps = n_utils = 0
    for app in sorted(Gio.AppInfo.get_all(), key=lambda a: a.get_display_name().lower()):
        if not app.should_show():
            continue
        app_id = app.get_id().removesuffix(".desktop")
        if app_id in prefs:
            continue
        if app_id in utilities:
            write(utils_dir, app)
            n_utils += 1
        else:
            write(dest, app)
            n_apps += 1
    print(f"{dest}: アプリケーション {n_apps} 個、ユーティリティ {n_utils} 個")


if __name__ == "__main__":
    main()
