#!/bin/bash
# config/hidden-apps.txt の一覧から、メニューに出さないための .desktop (NoDisplay=true) を作る。
# 出力: config/skel/.local/share/applications/
# 使い方: scripts/gen-hidden-apps.sh
set -eu

root="$(cd "$(dirname "$0")/.." && pwd)"
list="$root/config/hidden-apps.txt"
out="$root/config/skel/.local/share/applications"

mkdir -p "$out"
# 前回の生成物を消す (hidden-apps.txt から外したものを元に戻すため)
find "$out" -maxdepth 1 -name '*.desktop' -exec grep -l '^# generated by gen-hidden-apps.sh' {} + 2>/dev/null | xargs -r rm -f

n=0
while read -r id; do
    case "$id" in ''|'#'*) continue ;; esac
    if [ ! -f "/usr/share/applications/$id.desktop" ]; then
        echo "警告: /usr/share/applications/$id.desktop がありません" >&2
    fi
    printf '# generated by gen-hidden-apps.sh\n[Desktop Entry]\nType=Application\nName=%s\nExec=true\nNoDisplay=true\nHidden=true\n' "$id" > "$out/$id.desktop"
    n=$((n + 1))
done < "$list"
echo "$n 個のアプリをメニューから隠す設定を作りました: $out"
